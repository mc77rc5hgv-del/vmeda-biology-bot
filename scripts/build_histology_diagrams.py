OUT = Path(__file__).resolve().parents[1] / "images/histology/teaching"
INK = "#182238"
COLORS = ["#eadcf5", "#d2b8e8", "#eee3cb", "#bbdce7", "#d4e8d5", "#edcbd0"]


def canvas(title, subtitle):
    fig, ax = plt.subplots(figsize=(12, 9), dpi=150)
    fig.patch.set_facecolor("#faf9fc")
    ax.set_xlim(0, 12)
    ax.set_ylim(0, 9)
    ax.axis("off")
    ax.text(.4, 8.5, title, size=23, weight="bold", color=INK)
    ax.text(.4, 7.9, subtitle, size=12, color="#62677a")
    ax.text(.4, .2, "VMEDA • Учебная схема, не микрофотография • Не в масштабе", size=11, color="#62677a")
    return fig, ax


def save(fig, name):
    OUT.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT / name, bbox_inches="tight", facecolor=fig.get_facecolor())
    plt.close(fig)


def layers(title, subtitle, rows, name, footer):
    fig, ax = canvas(title, subtitle)
    height = min(.86, 5.8 / len(rows))
    for n, (label, detail) in enumerate(rows):
        y = 7.15 - n * height
        ax.add_patch(Rectangle((.45, y-height+.05), 11.1, height-.09,
                               color=COLORS[n % len(COLORS)]))
        ax.text(.7, y-height/2, label, size=13, weight="bold", color=INK, va="center")
        ax.text(5.25, y-height/2, detail, size=11, color=INK, va="center")
    ax.text(.5, .85, footer, size=12, color=INK)
    save(fig, name)


def flow(title, subtitle, rows, name, foot):
    fig, ax = canvas(title, subtitle)
    for n, text in enumerate(rows):
        y = 6.8-n*1.15
        ax.add_patch(Rectangle((1, y-.6), 10, .85, facecolor=COLORS[n % len(COLORS)],
                               edgecolor="#bbb0cd", linewidth=1))
        ax.text(6, y-.18, text, size=15, color=INK, ha="center", va="center")
        if n < len(rows)-1:
            ax.annotate("", xy=(6,y-.83), xytext=(6,y-.61),
                        arrowprops=dict(arrowstyle="->", color="#6d438d", lw=2))
    ax.text(.5, .85, foot, size=12, color=INK)
    save(fig, name)


