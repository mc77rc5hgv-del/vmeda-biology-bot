# Общая для всех типов заданий часть follow-up'а: явно указывает модели опираться на уже данный
# краткий ответ (canonical answer), а не решать заново с нуля — без этого якоря детальный разбор
# мог уйти к другой модели-провайдеру (см. ai.router.route_bucket) и разойтись с быстрым ответом в
# методе округления/подходе/выбранном варианте (наблюдалось на реальных задачах, см. CLAUDE.md).
_EXPLAIN_ANCHOR = (
    "Ты уже дал краткий ответ на это задание: «{quick_answer}». Не меняй итоговый результат "
    "(число, выбранный вариант, названные термины) — только раскрой его подробнее; если по ходу "
    "объяснения заметишь ошибку в этом ответе, прямо укажи на неё, но не подменяй результат "
    "незаметно.\n\n"
)

# Реальный пример, который вскрыл проблему (см. CLAUDE.md): на списочный анатомический вопрос
# («брюшина / полость брюшины / брюшная полость / плевра / ...») старый универсальный follow-up
# («объясни, как получить ИМЕННО этот ответ») заставлял модель описывать процесс СОБСТВЕННОГО
# рассуждения («сначала я определил термины, затем собрал информацию...») вместо содержательного
# материала — для calculation-заданий та же формулировка работает нормально (там реально нужно
# показать шаги вычисления), но для list/theory она системно давала бесполезный ответ. Раз follow-
# up для одного и того же квадратного разговора требует РАЗНОГО поведения в зависимости от того,
# что вообще за задание, ветвим по task.type (см. ai/task.py, TASK_TYPES) вместо одной формулировки
# на все случаи.
