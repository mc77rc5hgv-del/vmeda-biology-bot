# Follow-up для подробного разбора — форма ЗАВИСИТ от task.type (см. _EXPLAIN_* выше и разбор
# конкретного провалившегося кейса в их комментарии): один общий якорь (canonical answer, чтобы
# детальный разбор не разошёлся с кратким при уходе на другого провайдера) + разная инструкция по
# СОДЕРЖАНИЮ в зависимости от типа задания.
def explain_followup_text(quick_answer: str, task_type: str | None = None) -> str:
    anchor = _EXPLAIN_ANCHOR.format(quick_answer=quick_answer)
    body = {
        "calculation": _EXPLAIN_CALCULATION,
        "mcq": _EXPLAIN_MCQ,
        "list": _EXPLAIN_LIST_THEORY,
        "theory": _EXPLAIN_LIST_THEORY,
    }.get(task_type, _EXPLAIN_DEFAULT)
    return anchor + body
