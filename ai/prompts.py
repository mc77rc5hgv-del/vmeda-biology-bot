def subject_guidance_for(subject: str | None) -> str:
    return SUBJECT_GUIDANCE.get(subject or "", "")


def system_prompt_for(subject: str | None) -> str:
    guidance = subject_guidance_for(subject)
    return SYSTEM_PROMPT + ANSWER_QUALITY_STANDARD + (("\n\n" + guidance) if guidance else "")


def expansion_followup_text(task) -> str:
    guidance = subject_guidance_for(getattr(task, "subject", None))
    original = task.to_prompt_text() if task is not None else ""
    return (
        "Предыдущий ответ получился слишком коротким для учебного теоретического вопроса. "
        "Перепиши его полностью, а не дописывай одну фразу. Дай прямое определение, затем "
        "структурированный разбор всех существенных частей темы и короткий итог для запоминания. "
        "Строго выполни требования исходной формулировки пользователя. Не рассказывай о процессе "
        "своего рассуждения.\n\n"
        + (guidance + "\n\n" if guidance else "")
        + "Исходное задание:\n" + original
    )


